const DIAGNOSTICS_FILENAME: &str = "halod-diagnostics.json";
const COPIED_FEEDBACK_SECS: f64 = 1.8;

pub(crate) fn copied_feedback_visible(copied_at: Option<f64>, now: f64) -> bool {
    copied_at.is_some_and(|at| now >= at && now - at < COPIED_FEEDBACK_SECS)
}

/// Open a save dialog and write `json` to the chosen file on a worker thread,
/// so the UI frame is never blocked by the native picker.
